#!/usr/bin/env python3
"""User configuration provisioning, timestamped backup, and restore for NC-UI."""

from datetime import datetime
import json
import os
import re
import shutil
import subprocess

from core import probe
from core.paths import find_package_file

_NIRI_MARKER = "// managed-by: nc-ui"


def _use_color() -> bool:
    return "NO_COLOR" not in os.environ


def _c(code: str, text: str) -> str:
    return f"\033[{code}m{text}\033[0m" if _use_color() else text


def _tag(kind: str) -> str:
    colors = {
        "BACKUP": "1;93",
        "RESTORE": "1;95",
        "OK": "1;92",
        "INFO": "1;96",
        "WARN": "1;93",
        "ERR": "1;91",
    }
    return _c(colors.get(kind, "1"), f"[{kind}]")


def _xdg_config_home() -> str:
    return os.path.expanduser(os.environ.get("XDG_CONFIG_HOME", "").strip() or "~/.config")


def _xdg_data_home() -> str:
    return os.path.expanduser(os.environ.get("XDG_DATA_HOME", "").strip() or "~/.local/share")


def niri_dir() -> str:
    return os.path.join(_xdg_config_home(), "niri")


def waybar_dir() -> str:
    return os.path.join(_xdg_config_home(), "waybar")


def ncui_cfg_dir() -> str:
    return os.path.join(_xdg_config_home(), "ncui")


def backup_root() -> str:
    return os.path.join(_xdg_data_home(), "ncui", "backups")


def _is_waybar_ncui_managed(wb_dir: str) -> bool:
    if os.path.lexists(os.path.join(wb_dir, "config")):
        return False
    cfg_p = os.path.join(wb_dir, "config.jsonc")
    css_p = os.path.join(wb_dir, "style.css")
    if not os.path.isfile(cfg_p) or not os.path.isfile(css_p):
        return False
    try:
        cfg_txt = open(cfg_p, "r", encoding="utf-8", errors="ignore").read()
        css_txt = open(css_p, "r", encoding="utf-8", errors="ignore").read()
    except OSError:
        return False
    has_cfg = ('"nc-bar-agent' in cfg_txt) or ('"nc-ctl' in cfg_txt)
    has_css = (".module-nc" in css_txt) or ("nc-glow-pulse" in css_txt)
    return has_cfg and has_css


def _has_ncui_kdl_include(kdl_text: str) -> bool:
    return bool(re.search(r'(?m)^\s*include\b[^#\n]*"ncui\.kdl"', kdl_text or ""))


def _reload_waybar_if_running(dry_run: bool = False) -> None:
    if dry_run or os.environ.get("NC_SETUP_NO_RELOAD") == "1":
        return
    if not probe.has_bin("pgrep"):
        return
    ok, _ = probe.run_cmd(["pgrep", "-u", str(os.getuid()), "-x", "waybar"], timeout=1.0)
    if ok:
        try:
            subprocess.Popen(
                ["pkill", "-SIGUSR2", "waybar"],
                stdin=subprocess.DEVNULL,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                start_new_session=True,
            )
        except Exception:
            pass


def _new_backup_session(dry_run: bool = False) -> dict:
    ts = datetime.now().strftime("%Y%m%d-%H%M%S")
    bdir = os.path.join(backup_root(), f"pre-ncui-{ts}")
    if not dry_run and os.path.exists(bdir):
        idx = 1
        while os.path.exists(f"{bdir}_{idx}"):
            idx += 1
        bdir = f"{bdir}_{idx}"
    return {"dir": bdir, "ts": ts, "dry_run": dry_run, "files": [], "created": [], "backed_up": set()}


def _backup_file(sess: dict, src_path: str, rel_key: str) -> str:
    if not os.path.lexists(src_path) or src_path in sess["backed_up"]:
        return ""
    dst_path = os.path.join(sess["dir"], rel_key)
    prefix = "(dry-run) " if sess["dry_run"] else ""
    if not sess["dry_run"]:
        os.makedirs(os.path.dirname(dst_path), exist_ok=True)
        shutil.copy2(src_path, dst_path)
    sess["backed_up"].add(src_path)
    sess["files"].append({"orig": src_path, "rel": rel_key})
    print(f"{_tag('BACKUP')} {prefix}{_c('1;97', src_path)} -> {_c('1;96', dst_path)}")
    return dst_path


def _record_created(sess: dict, path: str) -> None:
    if path not in sess["created"]:
        sess["created"].append(path)


def _write_manifest(sess: dict) -> bool:
    if sess["dry_run"] or (not sess["files"] and not sess["created"]):
        return False
    os.makedirs(sess["dir"], exist_ok=True)
    manifest = {
        "created_at": datetime.now().isoformat(timespec="seconds"),
        "files": sess["files"],
        "created": sess["created"],
    }
    with open(os.path.join(sess["dir"], "manifest.json"), "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)
    return True


def _build_ncui_kdl(existing_kdl: str) -> str:
    txt = existing_kdl or ""
    lines = [
        _NIRI_MARKER,
        "// Generated by 'nc-ctl setup'. Safe to regenerate with '--force'.",
        "",
    ]

    spawns: list[str] = []
    if not re.search(r'(?m)^\s*spawn-at-startup\s+"awww-daemon"', txt):
        spawns.append('spawn-at-startup "awww-daemon"')
    if not re.search(r'(?m)^\s*spawn-at-startup\b[^\n]*(?:"nc-ctl"[^\n]*"wallpaper"|"nc-desktop\.sh")', txt):
        spawns.append('spawn-at-startup "nc-ctl" "wallpaper" "restore"')
    if not re.search(r'(?m)^\s*spawn-at-startup\b[^\n]*"nc-ctl"[^\n]*"popup"[^\n]*"hotkeys"', txt):
        spawns.append('spawn-at-startup "nc-ctl" "popup" "hotkeys"')
    if not re.search(r'(?m)^\s*spawn-at-startup\s+"waybar"', txt):
        spawns.append('spawn-at-startup "waybar"')
    if not re.search(r'(?m)^\s*spawn-at-startup\s+"wl-paste"[^\n]*"text"', txt):
        spawns.append('spawn-at-startup "wl-paste" "--type" "text" "--watch" "cliphist" "store"')
    if not re.search(r'(?m)^\s*spawn-at-startup\s+"wl-paste"[^\n]*"image"', txt):
        spawns.append('spawn-at-startup "wl-paste" "--type" "image" "--watch" "cliphist" "store"')
    if spawns:
        lines.extend(spawns)
        lines.append("")

    if not re.search(r"(?m)^\s*hotkey-overlay\s*\{", txt):
        lines.extend([
            "hotkey-overlay {",
            "    skip-at-startup",
            "}",
            "",
        ])

    binds: list[str] = []
    if not re.search(r'(?m)^\s*Mod\+Shift\+Slash\b|"hotkeys"', txt):
        binds.append('    Mod+Shift+Slash { spawn "nc-ctl" "popup" "hotkeys"; }')
    if not re.search(r'(?m)^\s*Mod\+I\b|"settings"', txt):
        binds.append('    Mod+I { spawn "nc-ctl" "popup" "settings"; }')
    if not re.search(r'(?m)^\s*(?:Mod\+)?Print\b|"capture"', txt):
        binds.append('    Mod+Print { spawn "nc-ctl" "action" "capture" "repeat"; }')
    if binds:
        lines.append("binds {")
        lines.extend(binds)
        lines.append("}")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def _setup_ncui_configs(sess: dict, force: bool = False) -> None:
    dst_dir = ncui_cfg_dir()
    dry = sess["dry_run"]
    for fname in ("config.toml", "theme.toml"):
        tpl = find_package_file("config", "ncui", fname)
        if not tpl or not os.path.isfile(tpl):
            continue
        dst = os.path.join(dst_dir, fname)
        if os.path.exists(dst):
            if not force:
                continue
            _backup_file(sess, dst, os.path.join("ncui", fname))
        else:
            _record_created(sess, dst)
        if not dry:
            os.makedirs(dst_dir, exist_ok=True)
            shutil.copy2(tpl, dst)
        print(f"{_tag('OK')} {'(dry-run) ' if dry else ''}Seeded {_c('1;97', dst)}")


def _setup_niri(sess: dict, force: bool = False) -> tuple[bool, str]:
    ndir = niri_dir()
    cfg_p = os.path.join(ndir, "config.kdl")
    ncui_kdl_p = os.path.join(ndir, "ncui.kdl")
    dry = sess["dry_run"]

    orig_cfg = ""
    cfg_existed = os.path.isfile(cfg_p)
    if cfg_existed:
        try:
            orig_cfg = open(cfg_p, "r", encoding="utf-8").read()
        except OSError as e:
            return False, f"Cannot read {cfg_p}: {e}"

    ncui_existed = os.path.lexists(ncui_kdl_p)
    ncui_is_managed = False
    if ncui_existed and os.path.isfile(ncui_kdl_p):
        try:
            with open(ncui_kdl_p, "r", encoding="utf-8", errors="ignore") as f:
                ncui_is_managed = f.read().lstrip().startswith(_NIRI_MARKER)
        except OSError:
            ncui_is_managed = False

    write_ncui_kdl = True
    if ncui_existed:
        if ncui_is_managed and not force:
            write_ncui_kdl = False
            print(f"{_tag('OK')} Niri include file already managed: {_c('1;97', ncui_kdl_p)}")
        else:
            _backup_file(sess, ncui_kdl_p, os.path.join("niri", "ncui.kdl"))
    else:
        _record_created(sess, ncui_kdl_p)

    if write_ncui_kdl:
        kdl_body = _build_ncui_kdl(orig_cfg)
        if not dry:
            os.makedirs(ndir, exist_ok=True)
            with open(ncui_kdl_p, "w", encoding="utf-8") as f:
                f.write(kdl_body)
        print(f"{_tag('OK')} {'(dry-run) ' if dry else ''}Wrote {_c('1;97', ncui_kdl_p)}")

    if not cfg_existed:
        _record_created(sess, cfg_p)
        new_cfg = '// Niri configuration\ninclude optional=true "ncui.kdl"\n'
        if not dry:
            os.makedirs(ndir, exist_ok=True)
            with open(cfg_p, "w", encoding="utf-8") as f:
                f.write(new_cfg)
        print(f"{_tag('OK')} {'(dry-run) ' if dry else ''}Created {_c('1;97', cfg_p)} with ncui.kdl include")
    elif not _has_ncui_kdl_include(orig_cfg):
        cfg_bak = _backup_file(sess, cfg_p, os.path.join("niri", "config.kdl"))
        new_cfg = orig_cfg.rstrip() + '\n\n// NC-UI integration\ninclude optional=true "ncui.kdl"\n'
        if not dry:
            with open(cfg_p, "w", encoding="utf-8") as f:
                f.write(new_cfg)
            if probe.has_bin("niri"):
                ok, _out, err = probe.run_cmd_full(["niri", "validate", "-c", cfg_p], timeout=2.5)
                if not ok:
                    if cfg_bak and os.path.isfile(cfg_bak):
                        shutil.copy2(cfg_bak, cfg_p)
                    return False, f"niri validate failed (rolled back): {err or 'syntax error'}"
        print(f"{_tag('OK')} {'(dry-run) ' if dry else ''}Linked ncui.kdl in {_c('1;97', cfg_p)}")
    else:
        print(f"{_tag('OK')} Niri config already includes ncui.kdl: {_c('1;97', cfg_p)}")

    return True, ""


def _setup_waybar(sess: dict, force: bool = False) -> tuple[bool, str]:
    tpl_cfg = find_package_file("config", "waybar", "config.jsonc")
    tpl_css = find_package_file("config", "waybar", "style.css")
    if not tpl_cfg or not tpl_css or not os.path.isfile(tpl_cfg) or not os.path.isfile(tpl_css):
        print(f"{_tag('INFO')} Waybar templates not found (nc-ui-waybar not installed); skipping Waybar setup.")
        return True, ""

    wb_dir = waybar_dir()
    if _is_waybar_ncui_managed(wb_dir) and not force:
        print(f"{_tag('OK')} Waybar config already NC-UI managed: {_c('1;97', wb_dir)}")
        return True, ""

    dry = sess["dry_run"]
    extless = os.path.join(wb_dir, "config")
    cfg_dst = os.path.join(wb_dir, "config.jsonc")
    css_dst = os.path.join(wb_dir, "style.css")

    if os.path.lexists(extless):
        _backup_file(sess, extless, os.path.join("waybar", "config"))
        if not dry:
            os.unlink(extless)
    if os.path.lexists(cfg_dst):
        _backup_file(sess, cfg_dst, os.path.join("waybar", "config.jsonc"))
    else:
        _record_created(sess, cfg_dst)
    if os.path.lexists(css_dst):
        _backup_file(sess, css_dst, os.path.join("waybar", "style.css"))
    else:
        _record_created(sess, css_dst)

    if not dry:
        os.makedirs(wb_dir, exist_ok=True)
        shutil.copy2(tpl_cfg, cfg_dst)
        shutil.copy2(tpl_css, css_dst)
        _reload_waybar_if_running(dry_run=False)

    print(f"{_tag('OK')} {'(dry-run) ' if dry else ''}Installed NC-UI Waybar config in {_c('1;97', wb_dir)}")
    return True, ""


def run_setup(dry_run: bool = False, force: bool = False, do_niri: bool = True, do_waybar: bool = True) -> int:
    """Provision NC-UI configs for Niri and Waybar with automatic timestamped backups."""
    if os.geteuid() == 0:
        print(f"{_tag('ERR')} Run 'nc-ctl setup' as your normal user, not root.")
        return 1

    sess = _new_backup_session(dry_run=dry_run)
    _setup_ncui_configs(sess, force=force)

    if do_niri:
        ok, err = _setup_niri(sess, force=force)
        if not ok:
            print(f"{_tag('ERR')} {err}")
            return 1
    if do_waybar:
        ok, err = _setup_waybar(sess, force=force)
        if not ok:
            print(f"{_tag('ERR')} {err}")
            return 1

    wrote_manifest = _write_manifest(sess)
    if sess["files"]:
        label = "would be saved" if dry_run else "saved"
        print(
            f"{_tag('BACKUP')} {len(sess['files'])} existing file(s) {label} in "
            f"{_c('1;96', sess['dir'])}  (restore anytime: {_c('1;93', 'nc-ctl setup --restore')})"
        )
    elif wrote_manifest:
        print(f"{_tag('INFO')} Setup manifest recorded in {_c('1;96', sess['dir'])}")
    else:
        print(f"{_tag('INFO')} No existing user files needed changes.")
    return 0


def _list_backups() -> list[str]:
    root = backup_root()
    if not os.path.isdir(root):
        return []
    dirs = [
        os.path.join(root, d)
        for d in sorted(os.listdir(root), reverse=True)
        if d.startswith("pre-ncui-") and os.path.isfile(os.path.join(root, d, "manifest.json"))
    ]
    return dirs


def run_restore(backup_dir: str = "", dry_run: bool = False) -> int:
    """Restore user configuration files from the latest or specified backup directory."""
    if os.geteuid() == 0:
        print(f"{_tag('ERR')} Run 'nc-ctl setup --restore' as your normal user, not root.")
        return 1

    target = os.path.expanduser(backup_dir.strip()) if backup_dir else ""
    if not target:
        avail = _list_backups()
        if not avail:
            print(f"{_tag('ERR')} No backups found in {_c('1;96', backup_root())}")
            return 1
        target = avail[0]

    manifest_p = os.path.join(target, "manifest.json")
    if not os.path.isfile(manifest_p):
        print(f"{_tag('ERR')} Invalid backup directory (missing manifest.json): {target}")
        return 1

    try:
        manifest = json.load(open(manifest_p, "r", encoding="utf-8"))
    except Exception as e:
        print(f"{_tag('ERR')} Cannot read {manifest_p}: {e}")
        return 1

    prefix = "(dry-run) " if dry_run else ""
    restored_wb = False
    niri_cfg = os.path.join(niri_dir(), "config.kdl")
    restored_niri = False

    for ent in manifest.get("files", []):
        orig = ent.get("orig", "")
        rel = ent.get("rel", "")
        src = os.path.join(target, rel)
        if not orig or not os.path.isfile(src):
            continue
        if not dry_run:
            os.makedirs(os.path.dirname(orig), exist_ok=True)
            shutil.copy2(src, orig)
        print(f"{_tag('RESTORE')} {prefix}{_c('1;96', src)} -> {_c('1;97', orig)}")
        if rel.startswith("waybar" + os.sep) or rel.startswith("waybar/"):
            restored_wb = True
        if orig == niri_cfg:
            restored_niri = True

    for created_p in manifest.get("created", []):
        if created_p and os.path.lexists(created_p):
            if not dry_run:
                os.unlink(created_p)
            print(f"{_tag('RESTORE')} {prefix}Removed created file {_c('1;97', created_p)}")
            if "waybar" in created_p:
                restored_wb = True

    if restored_niri and not dry_run and os.path.isfile(niri_cfg) and probe.has_bin("niri"):
        ok, _out, err = probe.run_cmd_full(["niri", "validate", "-c", niri_cfg], timeout=2.5)
        if not ok:
            print(f"{_tag('WARN')} niri validate reported: {err}")

    if restored_wb:
        _reload_waybar_if_running(dry_run=dry_run)

    print(f"{_tag('OK')} {prefix}Restore completed from {_c('1;96', target)}")
    return 0


def run_status() -> int:
    """Print provisioning status of Niri, Waybar, NC-UI configs, and backups."""
    ndir = niri_dir()
    cfg_p = os.path.join(ndir, "config.kdl")
    ncui_kdl_p = os.path.join(ndir, "ncui.kdl")
    kdl_txt = open(cfg_p, "r", encoding="utf-8", errors="ignore").read() if os.path.isfile(cfg_p) else ""
    has_inc = _has_ncui_kdl_include(kdl_txt)
    has_ncui_kdl = os.path.isfile(ncui_kdl_p)

    wb_dir = waybar_dir()
    wb_managed = _is_waybar_ncui_managed(wb_dir)
    wb_has_files = any(os.path.lexists(os.path.join(wb_dir, f)) for f in ("config", "config.jsonc", "style.css"))

    print(f"{_tag('INFO')} Niri config:   {cfg_p} ({'includes ncui.kdl' if has_inc else 'no ncui.kdl include'})")
    print(f"{_tag('INFO')} Niri ncui.kdl: {ncui_kdl_p} ({'present' if has_ncui_kdl else 'missing'})")
    wb_state = "NC-UI managed" if wb_managed else ("custom / non-standard" if wb_has_files else "missing")
    print(f"{_tag('INFO')} Waybar dir:    {wb_dir} ({wb_state})")
    for fn in ("config.toml", "theme.toml"):
        p = os.path.join(ncui_cfg_dir(), fn)
        print(f"{_tag('INFO')} NC-UI {fn:11s}: {p} ({'present' if os.path.isfile(p) else 'missing'})")
    baks = _list_backups()
    print(f"{_tag('INFO')} Backups ({len(baks)}): {baks[0] if baks else 'none'}")
    return 0
