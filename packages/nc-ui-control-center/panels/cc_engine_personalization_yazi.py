def _build_xterm_256() -> tuple:
    pal = [(r / 255.0, g / 255.0, b / 255.0) for r, g, b in _XTERM_ANSI_16]
    steps = (0, 95, 135, 175, 215, 255)
    for r in range(6):
        for g in range(6):
            for b in range(6):
                pal.append((steps[r] / 255.0, steps[g] / 255.0, steps[b] / 255.0))
    for i in range(24):
        v = (8 + i * 10) / 255.0
        pal.append((v, v, v))
    return tuple(pal)


